/**
 * What is actually being sold. Each type gets its own page because a buyer of
 * a house, a buyer of an operation, and a lessee need different facts.
 *   realEstate — the building, licensed or AFH-ready, with or without the business
 *   business   — the operation (license history, residents, staff, contracts); real estate leased or sold separately
 *   lease      — the right to operate in someone else's house
 */
export type AFHListingType = "realEstate" | "business" | "lease";

/** Where the listing data came from. Drives attribution: NWMLS entries carry the NWMLS disclaimer; others link to the source. */
export type AFHListingSource = "nwmls" | "rmls" | "bizbuysell" | "direct";

/**
 * The home's relationship to AFH licensing, in the listing's own words.
 *   operating            — licensed and caring for residents today
 *   licensedNotOperating — licensed, no residents
 *   former               — previously licensed; buyer must relicense
 *   afhReady             — passed WABO / built to AFH code, never licensed
 *   opportunity          — marketed for potential AFH use; no code work claimed
 */
export type AFHStatus = "operating" | "licensedNotOperating" | "former" | "afhReady" | "opportunity";

/** Whether the operating business conveys with the real estate. "separate" means it is listed on its own (see linkedMls). */
export type AFHBusinessIncluded = "yes" | "no" | "separate" | "unknown";

/**
 * Where the listing stands in the market. Listings are never deleted from this
 * file when they leave the market — they are moved to sold / expired /
 * withdrawn so their page can say so. Only "active" and "pending" display
 * in the directory; the rest are historical.
 */
export type AFHMarketStatus = "active" | "pending" | "sold" | "expired" | "withdrawn";

export const AFH_MARKET_STATUS_LABELS: Record<AFHMarketStatus, string> = {
  active: "Active",
  pending: "Pending",
  sold: "Sold",
  expired: "Expired",
  withdrawn: "Withdrawn",
};

/** Statuses that count as currently on the market. */
export const AFH_LIVE_STATUSES: readonly AFHMarketStatus[] = ["active", "pending"];

export interface AFHListing {
  id: number;
  /** Current market status. Change this instead of deleting the record when a listing leaves the market. */
  marketStatus: AFHMarketStatus;
  /**
   * ISO date (YYYY-MM-DD) the status and price were last checked against the
   * source. Displayed on the page as "Last verified …" and emitted as
   * dateModified in structured data, so it must reflect a real check —
   * a stale date is worse than none.
   */
  lastVerified: string;
  /** ISO date the status last changed (went pending, sold, expired). Required for any non-active record. */
  statusChanged?: string;
  /** ISO date the listing first hit the market, if known. Enables days-on-market on the sold page. */
  listedDate?: string;
  /** Closing price, e.g. "$1,850,000". Sold records only. Leave out if NWMLS display rules don't permit it. */
  soldPrice?: string;
  /** ISO closing date. Required for sold records. */
  soldDate?: string;
  listingType: AFHListingType;
  source: AFHListingSource;
  /** Listing page at the source. Required for non-NWMLS sources; that link IS the attribution. */
  sourceUrl?: string;
  afhStatus: AFHStatus;
  businessIncluded: AFHBusinessIncluded;
  /** MLS number of the companion listing — the business for a real-estate entry, or vice versa. */
  linkedMls?: string;
  address: string;
  city: string;
  state: string;
  beds: number;
  bathDisplay: string;
  bathDetail: string;
  sqft: string;
  price: string;
  priceLabel?: string;
  photo: string | null;
  /** Listing agent. Optional because some non-NWMLS sources publish only the office. */
  broker?: string;
  brokerage: string;
  /** MLS or source listing number. */
  mlsNum: string;
  /** Business-only and lease listings: licensed capacity, current census, contracts, term. Free text, shown verbatim. */
  businessNotes?: string;
}

export const AFH_STATUS_LABELS: Record<AFHStatus, string> = {
  operating: "Operating AFH",
  licensedNotOperating: "Licensed AFH — no residents",
  former: "Former AFH",
  afhReady: "AFH-ready (WABO)",
  opportunity: "AFH potential — not verified",
};

export const AFH_SOURCE_LABELS: Record<AFHListingSource, string> = {
  nwmls: "NWMLS",
  rmls: "RMLS",
  bizbuysell: "BizBuySell",
  direct: "Direct from seller",
};

export const AFH_TYPE_LABELS: Record<AFHListingType, { singular: string; plural: string; slug: string }> = {
  realEstate: { singular: "Property for sale", plural: "Properties for sale", slug: "properties" },
  business: { singular: "Business for sale", plural: "Businesses for sale", slug: "businesses" },
  lease: { singular: "For lease", plural: "For lease", slug: "for-lease" },
};

/** Human label for the classification shown on cards: status plus what conveys. */
export function afhClassification(l: AFHListing): string {
  if (l.listingType === "business") return "AFH business only";
  if (l.listingType === "lease") return "AFH property for lease";
  const base = AFH_STATUS_LABELS[l.afhStatus];
  if (l.afhStatus === "operating" || l.afhStatus === "licensedNotOperating") {
    if (l.businessIncluded === "yes") return `${base} + real estate`;
    if (l.businessIncluded === "separate") return `${base} — business listed separately`;
    if (l.businessIncluded === "no") return `${base} — business not included`;
  }
  return base;
}

export const isLive = (l: AFHListing) => AFH_LIVE_STATUSES.includes(l.marketStatus);

/** Listings currently on the market (active or pending). This is what every page displays. */
export const liveListings = (): AFHListing[] => afhListings.filter(isLive);

export const listingsByType = (type: AFHListingType) => liveListings().filter((l) => l.listingType === type);

/** "September 13, 2026" from "2026-09-13". Parsed as UTC noon so the day never shifts across time zones. */
export function formatVerifiedDate(iso: string): string {
  const d = new Date(`${iso}T12:00:00Z`);
  return d.toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });
}

/** URL slug for a listing's permanent page: /afh-club/listings/<city>-<source>-<number>. Stable across status changes. */
export function listingSlug(l: AFHListing): string {
  const city = l.city.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
  return `${city}-${l.source}-${l.mlsNum.toLowerCase().replace(/[^a-z0-9]+/g, "-")}`;
}

export const findListingBySlug = (slug: string): AFHListing | undefined =>
  afhListings.find((l) => listingSlug(l) === slug);

/** Listings that have closed, newest first. */
export const soldListings = (): AFHListing[] =>
  afhListings.filter((l) => l.marketStatus === "sold").sort((a, b) => (b.soldDate ?? "").localeCompare(a.soldDate ?? ""));

/** Most recent lastVerified across a set of listings, as an ISO date. */
export function latestVerified(listings: AFHListing[]): string | null {
  return listings.reduce<string | null>((max, l) => (max === null || l.lastVerified > max ? l.lastVerified : max), null);
}

