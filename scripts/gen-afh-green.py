import re,tinycss2,sys
src=open(sys.argv[1]).read()
MAP=[(r'#8F1A2B','#0a5648'),(r'#9E1F3A','#0a5648'),(r'#84182F','#084238'),(r'#1B3A6B','#0a5648'),(r'#142c52','#084238'),
     (r'#6b84ad','#4f8a7c'),(r'#b9c6dc','#b5d3ca'),(r'#eef2f8','#eef5f2'),
     (r'rgba?\(\s*143\s*,\s*26\s*,\s*43','rgba(10, 86, 72'),(r'rgba?\(\s*27\s*,\s*58\s*,\s*107','rgba(10, 86, 72'),(r'rgba?\(\s*158\s*,\s*31\s*,\s*58','rgba(10, 86, 72')]
PAT=re.compile('|'.join(m[0] for m in MAP),re.I)
def swap(v):
    for a,b in MAP:
        v2=re.sub(a,b,v,flags=re.I)
        if v2!=v and b.startswith('rgba(') and re.search(a+r'\s*\)',v,re.I):  # rgb(...) with 3 args -> close properly
            v2=re.sub(a+r'(\s*)\)',r'rgba(10, 86, 72\1)',v,flags=re.I)
        v=v2
    return v
def scope(sel):
    """Same specificity as the original selector (so a page's own, more
    specific override still wins), scoped to AFH Club. This file loads after
    index.css, so on a tie it wins."""
    s=sel.strip()
    if not s or s.startswith(':root') or s in('html','body') or s.startswith('@'): return None
    if re.match(r'^html\.dark|^\.dark',s): return None
    if re.match(r'^html(?![\w-])',s): return 'html:where(.rpp-afh)'+s[4:]
    if re.search(r'(^|[\s>+~(])main(?![\w-])',s): return ':where(html.rpp-afh) '+s
    return ':where(html.rpp-afh main) '+s
out=[]
def walk(rules,depth=0,wrap=None):
    for r in rules:
        if r.type=='qualified-rule':
            decls=tinycss2.parse_declaration_list(r.content,skip_whitespace=True,skip_comments=True)
            keep=[]
            for d in decls:
                if d.type!='declaration': continue
                v=tinycss2.serialize(d.value)
                if PAT.search(v) and not d.name.startswith('--'):
                    keep.append(f"{d.name}: {swap(v).strip()}{' !important' if d.important else ''};")
            if keep:
                sels=[scope(x) for x in tinycss2.serialize(r.prelude).split(',')]
                # naive split breaks :where(a,b) -> rejoin if parens unbalanced
                raw=tinycss2.serialize(r.prelude); parts=[];buf='';dep=0
                for ch in raw:
                    if ch=='(':dep+=1
                    if ch==')':dep-=1
                    if ch==',' and dep==0: parts.append(buf);buf=''
                    else: buf+=ch
                parts.append(buf)
                sels=[x for x in (scope(p) for p in parts) if x]
                if sels:
                    body="\n  ".join(keep)
                    out.append((wrap,f"{', '.join(sels)} {{\n  {body}\n}}"))
        elif r.type=='at-rule' and r.lower_at_keyword in('media','supports') and r.content:
            inner=tinycss2.parse_rule_list(r.content,skip_whitespace=True,skip_comments=True)
            walk(inner,depth+1,f"@{r.lower_at_keyword} {tinycss2.serialize(r.prelude).strip()}")
walk(tinycss2.parse_stylesheet(src,skip_whitespace=True,skip_comments=True))
res=["/* GENERATED by scripts/gen-afh-green.py from src/index.css. Do not edit by hand.\n   AFH Club (html.rpp-afh, any /afh-club page): every garnet or navy accent\n   inside <main> becomes AFH Club hunter green (#0a5648). Nov 22, 2026. */",
"""html.rpp-afh {
  /* Shared components read these (fallback: their main-site colour). */
  --rpp-accent: #0a5648;
  --rpp-accent-dark: #084238;
  --rpp-accent-soft: #b5d3ca;
}

html.rpp-afh main .rpp-page-faq-toggle svg, html.rpp-afh main .rpp-page-faq-toggle svg * { stroke: #0a5648 !important; }

html.rpp-afh main {
  --gold: 169 79% 19%;
  --gold-dark: 169 79% 14%;
  --gold-light: 160 25% 55%;
  --primary: 169 79% 19%;
  --ring: 169 79% 19%;
  --accent: 169 79% 19%;
}"""]
for w,t in out:
    res.append(f"{w} {{\n{t}\n}}" if w else t)
open(sys.argv[2],'w').write("\n\n".join(res)+"\n")
print(len(out))
