#!/usr/bin/env node
/**
 * Inject the adult family home directory URLs into public/sitemap.xml.
 *
 *   node scripts/generate-directory-sitemap.mjs
 *   node scripts/generate-directory-sitemap.mjs --facilities   (adds facility pages)
 *
 * The directory routes are dynamic (/afh-club/homes/:citySlug), so a script that
 * reads App.tsx cannot enumerate them — they have to be expanded from the data.
 *
 * Writes between marker comments and replaces whatever is already there, so this
 * is safe to re-run every time the DSHS data is refreshed.
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://realpropertyplanning.com";
const SITEMAP = join(root, "public", "sitemap.xml");
const START = "  <!-- BEGIN afh-directory (generated by scripts/generate-directory-sitemap.mjs) -->";
const END = "  <!-- END afh-directory -->";

/**
 * A filter page with only one or two homes is a thin result, and submitting a
 * few hundred of those is how a site teaches Google that its pages aren't worth
 * indexing. Filter pages below this threshold stay reachable by link but are
 * kept out of the sitemap.
 */
const MIN_FILTER_RESULTS = 3;

// Mirrors AFH_FILTERS in src/data/afh/directory.ts. Kept as plain predicates so
// this script needs no TypeScript toolchain to run.
const FILTERS = [
  ["specialized-behavior-support", (f) => f.contracts.includes("specializedBehaviorSupport")],
  ["developmental-disabilities", (f) => f.specialties.includes("developmentalDisabilities")],
  ["expanded-community-services", (f) => f.contracts.includes("expandedCommunityServices")],
  ["private-pay", (f) => !f.acceptsMedicaid],
  ["more-than-six-beds", (f) => f.licensedBeds > 6],
];

const includeFacilities = process.argv.includes("--facilities");
const today = new Date().toISOString().slice(0, 10);

const url = (path, priority, changefreq = "monthly") =>
  `  <url><loc>${SITE}${path}</loc><lastmod>${today}</lastmod>` +
  `<changefreq>${changefreq}</changefreq><priority>${priority}</priority></url>`;

const citiesDir = join(root, "src", "data", "afh", "cities");
const cityFiles = readdirSync(citiesDir).filter((f) => f.endsWith(".json"));

const lines = [START];
lines.push(url("/afh-club/homes", "0.8"));

let cityCount = 0;
let filterCount = 0;
let filterSkipped = 0;
let facilityCount = 0;

for (const file of cityFiles.sort()) {
  const citySlug = file.replace(/\.json$/, "");
  const facilities = JSON.parse(readFileSync(join(citiesDir, file), "utf8"));

  lines.push(url(`/afh-club/homes/${citySlug}`, "0.7"));
  cityCount++;

  for (const [slug, matches] of FILTERS) {
    const n = facilities.filter(matches).length;
    if (n < MIN_FILTER_RESULTS) {
      filterSkipped++;
      continue;
    }
    lines.push(url(`/afh-club/homes/${citySlug}/${slug}`, "0.6"));
    filterCount++;
  }

  if (includeFacilities) {
    // Only homes with DSHS documents on file — the rest have nothing
    // substantive to say yet and would be thin pages at scale.
    for (const f of facilities.filter((f) => f.hasReports)) {
      lines.push(url(`/afh-club/homes/${citySlug}/${f.slug}`, "0.5"));
      facilityCount++;
    }
  }
}
lines.push(END);

const xml = readFileSync(SITEMAP, "utf8");
const block = lines.join("\n");

let next;
if (xml.includes(START)) {
  next = xml.replace(new RegExp(`${escapeRe(START)}[\\s\\S]*?${escapeRe(END)}`), block);
} else {
  next = xml.replace("</urlset>", `${block}\n</urlset>`);
}
writeFileSync(SITEMAP, next);

const total = 1 + cityCount + filterCount + facilityCount;
console.error(`sitemap: ${total} directory URLs written`);
console.error(`  1 hub + ${cityCount} cities + ${filterCount} filter pages` +
  (includeFacilities ? ` + ${facilityCount} facility pages` : ""));
console.error(`  ${filterSkipped} filter pages skipped (fewer than ${MIN_FILTER_RESULTS} homes)`);
if (!includeFacilities) {
  console.error("  facility pages excluded — re-run with --facilities to include them");
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
